import hashlib,json,pathlib,tarfile
B=pathlib.Path(__file__).resolve().parents[1];O=B/'out';K=O/'guard_kit';import sys
sys.path.insert(0,str(K));from names import BAD
from guard_core import read,write,sha
rows=[]
paths=[(p,'code/'+str(p.relative_to(K))) for p in K.rglob('*') if p.is_file() and p.suffix in ('.py','.json','.sh')]
paths += [(O/'inputs'/name,'inputs/'+name) for name in ('reference.json','items.json')]
paths += [(O/'FAMILY.json','FAMILY.json')]
for p,name in sorted(paths,key=lambda x:x[1]):
 for number,line in enumerate(p.read_text().splitlines(),1):
  for m in BAD.finditer(line):
   reason=('Exact accepted item key; opaque runtime mapping is not integrated.' if name.startswith('inputs/') else
           'Inherited or reviewed source: code identifiers/prose are permitted; literal path/scope names require migration before launch.')
   rows.append(dict(file=name,line=number,column=m.start()+1,word=m.group(),text=line[:700],reason=reason))
with (O/'NAMING_OCCURRENCES.jsonl').open('w') as s:
 for r in rows:s.write(json.dumps(r,sort_keys=True)+'\n')
scan=read(O/'NAMING_SCAN.json');scan.update(total_occurrences=len(rows),code_occurrences=sum(x['file'].startswith('code/') for x in rows),input_occurrences=sum(x['file'].startswith('inputs/') for x in rows),family_occurrences=sum(x['file']=='FAMILY.json' for x in rows));write(O/'NAMING_SCAN.json',scan)
# Confirm package identity and regular archive headers without reusing builder assertions.
checks=[]
for file,manifest in [('code_g1.tar','CODE_MANIFEST.json'),('inputs_g1.tar','INPUT_MANIFEST.json')]:
 expected=read(O/manifest);found={}
 with tarfile.open(O/file) as t:
  for member in t:
   if not member.isfile() or member.name in found:raise ValueError('Archive member is not unique and regular')
   data=t.extractfile(member).read();found[member.name]=dict(bytes=len(data),sha256=hashlib.sha256(data).hexdigest())
 if found!=expected['members'] or sha(O/file)!=expected['sha256']:raise ValueError('Archive seal differs')
 checks.append(dict(path=str(O/file),sha256=sha(O/file),members=len(found),safe_regular_members=True,exact_manifest=True))
write(O/'ARCHIVE_VALIDATION.json',dict(status='PASS',archives=checks,large_inherited_input_archives_checked=False))
# No bytecode is generated by syntax validation.
count=0
for p in K.rglob('*.py'):compile(p.read_text(),str(p),'exec');count+=1
write(O/'SYNTAX.json',dict(status='PASS',files=count))
