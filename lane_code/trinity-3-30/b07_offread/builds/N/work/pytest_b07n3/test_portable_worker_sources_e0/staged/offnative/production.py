class Unserved:
    def __init__(self,model,processor,batch):
        self.model,self.processor,self.batch=model,processor,batch
    def generate(self,frames,question):
        # A native session without a mask source gives the inherited unserved response.
        P=install()
        _,batch=self.batch.prompt(frames,question)
        from student_pilot.carrier_c1_decode import generate
        session=P.session(None,None)
        def refuse(call):raise ValueError('unserved_secondary_arm')
        session.execute=refuse
        return generate(self.model,self.processor,batch,max_new_tokens=16384,trace_session=session)


class Runtime:
    synthetic=False
