HEADER = '| Topic | File | Status | Verdict | Evidence |'
SEP = '|---|---|---|---|---|'


def row(topic, files, status, verdict, evidence):
    cell = ' + '.join('`%s`' % f for f in files)
    return '| %s | %s | %s | %s | %s |' % (topic, cell, status, verdict, evidence)


def main():
    names = indexfmt.read_listing('ref/design_ls.txt')
    out = ['# Design records index (grouped)', '',
           'One row per record; evidence archives share their record\'s row. Evidence: OK, PARTIAL '
           '(cited raw outputs partly lost) or LOST-2-18 (the built artifact was only on trinity-2-18 '
           'or 2-28; "map N" = row N of `%s`). Add a row with `tools/docs/index_add.py`; '
           'superseded and closed rows live under Archive.' % MAP, '']
    seen = []
    problems = []
    for title, rows in GROUPS:
        out += ['## ' + title, HEADER, SEP]
        for item in rows:
            out.append(row(*item))
            seen += item[1]
        out.append('')
    out += ['## Archive', HEADER, SEP]
    for item in ARCHIVE:
        out.append(row(*item))
        seen += item[1]
    for line in out:
        if line.startswith('| ') and line != HEADER and len(line) > indexfmt.MAX_ROW_CHARS:
            problems.append('long row %d: %s' % (len(line), line[:70]))
    for title, rows in GROUPS + [('Archive', ARCHIVE)]:
        for item in rows:
            if len(item[2]) > indexfmt.MAX_STATUS_CHARS:
                problems.append('long status %d: %s' % (len(item[2]), item[1][0]))
    plain = [s.rstrip('/') for s in seen]
    for name in names:
        if plain.count(name) != 1:
            problems.append('count %d: %s' % (plain.count(name), name))
    for name in plain:
        if name not in names:
            problems.append('not in listing: %s' % name)
    main_lines = out.index('## Archive')
    sys.stdout.write('main lines %d, main rows %d, archive rows %d\n'
                     % (main_lines, sum(len(r) for _, r in GROUPS), len(ARCHIVE)))
    if problems:
        sys.stdout.write('\n'.join(problems) + '\n')
        return 1
    with open('out/INDEX_PROPOSED.md', 'w') as handle:
        handle.write('\n'.join(out) + '\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
